#!/usr/bin/env python3
"""Publish the configuration that produced the reported results, redacted.

config/config.example.yaml was the only configuration in the materials, and
it is a template: its extraction date, per-query cap and frame counts all
differ from the run, so following it would not reproduce the study. This
writes the real run configuration with every credential replaced by an
environment-variable placeholder, and refuses to write if anything that
looks like a secret survives.
"""
from __future__ import annotations
import pathlib, re, sys
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "config/config.main.yaml"
OUT = ROOT / "config/config.reported.yaml"
ENVVAR = {"youtube_api_key": "${YOUTUBE_API_KEY}",
          "anthropic_api_key": "${ANTHROPIC_API_KEY}",
          "google_api_key": "${GOOGLE_API_KEY}",
          "openai_api_key": "${OPENAI_API_KEY}"}
SECRETISH = re.compile(r"(?i)(api[_-]?key|secret|token|password|credential)")
LEAK = re.compile(r"(AIza[0-9A-Za-z_\-]{10,}|sk-[A-Za-z0-9]{12,}|ya29\.[\w\-]{10,})")

HEADER = """# The configuration that produced the reported results, with every
# credential replaced by an environment-variable placeholder. Generated by
# scripts/make_reported_config.py from the run configuration; do not edit.
#
# config/config.example.yaml remains a template and does NOT reproduce the
# study: its extraction date, per-query cap and frame counts differ from the
# run. Use this file.
"""


def redact(node):
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if k in ENVVAR:
                out[k] = ENVVAR[k]
            elif SECRETISH.search(str(k)):
                out[k] = "${REDACTED}"
            else:
                out[k] = redact(v)
        return out
    if isinstance(node, list):
        return [redact(x) for x in node]
    return node


def main() -> int:
    cfg = redact(yaml.safe_load(SRC.read_text()))
    body = yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True)
    text = HEADER + body
    if LEAK.search(body):
        print("refusing to write: a credential survived redaction")
        return 1
    for line in body.splitlines():          # the header is prose, not config
        if SECRETISH.search(line) and "${" not in line:
            print(f"refusing to write: unredacted secret-shaped key on: "
                  f"{line.split(':')[0].strip()}")
            return 1
    OUT.write_text(text)
    print(f"wrote {OUT}  ({len(text.splitlines())} lines)")
    print("  credentials present:", ", ".join(sorted(ENVVAR)), "-> placeholders")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
